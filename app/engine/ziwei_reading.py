GOOD_TEXT = "吉星同宫（{stars}）：助力明显，关键时刻容易有人拉一把。"
BAD_TEXT = "煞星同宫（{stars}）：过程易有波折与反复，宜留缓冲，避免硬碰硬。"


def _palace(chart: dict[str, Any], name: str) -> dict[str, Any]:
    return chart["palaces"][PALACE_INDEX[name]]


def _opposite(chart: dict[str, Any], name: str) -> dict[str, Any]:
    return chart["palaces"][(PALACE_INDEX[name] + 6) % 12]


def _main_stars(chart: dict[str, Any], name: str) -> tuple[list[str], bool]:
    """取主星；空宫时按传统「借对宫」处理，并回传是否借用。"""
    palace = _palace(chart, name)
    if palace["main"]:
        return list(palace["main"]), False
    return list(_opposite(chart, name)["main"]), True


def _aux_notes(palace: dict[str, Any]) -> list[str]:
    """吉星 / 煞星的补充提示。"""
    aux = set(palace["aux"])
    notes = []
    good = [s for s in AUSPICIOUS if s in aux]
    bad = [s for s in MALIFIC if s in aux]
    if good:
        notes.append(GOOD_TEXT.format(stars="、".join(good)))
    if bad:
        notes.append(BAD_TEXT.format(stars="、".join(bad)))
    return notes


def _si_hua_notes(palace: dict[str, Any]) -> list[str]:
    return [
        SI_HUA_TEXT[item["hua"]].format(star=item["star"])
        for item in palace["si_hua"]
        if item["hua"] in SI_HUA_TEXT
    ]


def _section(
    chart: dict[str, Any],
    palace_name: str,
    title: str,
    table: dict[str, str],
) -> dict[str, Any]:
    """把某宫的主星 + 辅星 + 四化翻译成一段解读。"""
    palace = _palace(chart, palace_name)
    main, borrowed = _main_stars(chart, palace_name)

    points = [table[s] for s in main if s in table]
    if borrowed and points:
        points[0] = f"本宫无主星（空宫），特质参照对宫「{main[0]}」：{points[0]}"
    points.extend(_si_hua_notes(palace))
    points.extend(_aux_notes(palace))

    if not points:  # pragma: no cover - 兜底：不出现空区块
        points = [STAR_TRAIT.get(main[0], "此宫星曜组合特殊，宜结合整盘参看。")
                  if main else "此宫星曜组合特殊，宜结合整盘参看。"]

    return {
        "title": title,
        "palace": palace_name,
        "zhi": palace["zhi"],
        "gan": palace["gan"],
        "stars": main,
        "borrowed": borrowed,
        "summary": points[0],
        "points": points,
    }


def build_ziwei_reading(chart: dict[str, Any]) -> dict[str, Any]:
    """把紫微命盘翻译成「感情 / 职业 / 运势」三块结论。"""
    love = _section(chart, "夫妻", "感情 · 夫妻宫", LOVE_TEXT)
    career = _section(chart, "官禄", "职业 · 官禄宫", CAREER_TEXT)
    wealth = _section(chart, "财帛", "财运 · 财帛宫", WEALTH_TEXT)
    fortune = _section(chart, "命宫", "运势基调 · 命宫", FORTUNE_TEXT)

    # 当前大限（十年一运）
    da_xian = chart["da_xian"]
    dx_stars = list(da_xian["main"])
    dx_palace_name = da_xian["palace"]
    dx_points = [DA_XIAN_TEXT[s] for s in dx_stars if s in DA_XIAN_TEXT]
    if not dx_points:
        dx_points = ["本步大限宫无主星，宜看对宫与四化综合判断。"]
    dx = {
        "title": "当前大限 · 十年运",
        "age": da_xian["age"],
        "range": f'{da_xian["from"]}-{da_xian["to"]} 岁',
        "palace": dx_palace_name,
        "zhi": da_xian["zhi"],
        "stars": dx_stars,
        "summary": dx_points[0],
        "points": dx_points,
    }

    # 命格一句话总结：命宫主星 + 三方四正
    ming_main = _main_stars(chart, "命宫")[0]
    san_fang = chart["san_fang"]
    pattern_stars = ming_main + [s for s in san_fang["career"]["main"]]
    headline = "、".join(ming_main) if ming_main else "空宫"
    if len(pattern_stars) >= 2:
        headline = f"{'、'.join(ming_main)}坐命，事业宫见{'、'.join(san_fang['career']['main']) or '空宫'}"

    career["wealth"] = {
        "palace": wealth["palace"],
        "zhi": wealth["zhi"],
        "stars": wealth["stars"],
        "points": wealth["points"],
    }
    fortune["da_xian"] = dx

    return {
        "headline": headline,
        "love": love,
        "career": career,
        "fortune": fortune,
    }
